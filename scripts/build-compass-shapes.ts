import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";

const root = path.join(import.meta.dirname, "..");
const inputPath = path.join(
    root,
    ".data",
    "raw",
    "ne_50m_admin_0_countries.geojson",
);
const outputPath = path.join(
    root,
    "src",
    "data",
    "generated",
    "compassShapes.ts",
);

interface Feature {
    properties?: {
        ADMIN?: string;
        SOVEREIGNT?: string;
        UN_A3?: string;
        TYPE?: string;
        ISO_A2?: string;
        ISO_A2_EH?: string;
    };
    geometry?: {
        type: "Polygon" | "MultiPolygon";
        coordinates: unknown;
    };
}

type Point = [number, number];

interface GeoShape {
    path: string;
    bounds: {
        minLon: number;
        maxLon: number;
        minLat: number;
        maxLat: number;
    };
}

function ringArea(ring: Point[]): number {
    let area = 0;
    for (let index = 0; index < ring.length; index += 1) {
        const current = ring[index];
        const next = ring[(index + 1) % ring.length];
        if (!current || !next) continue;
        area += current[0] * next[1] - next[0] * current[1];
    }
    return Math.abs(area / 2);
}

function simplify(ring: Point[], maxPoints = 28): Point[] {
    if (ring.length <= maxPoints) return ring;
    const step = (ring.length - 1) / (maxPoints - 1);
    return Array.from({ length: maxPoints }, (_, index) => {
        const point = ring[Math.round(index * step)];
        return point ?? ring[0] ?? [0, 0];
    });
}

function toPath(ring: Point[]): string {
    const bounds = ring.reduce(
        (result, [lon, lat]) => ({
            minLon: Math.min(result.minLon, lon),
            maxLon: Math.max(result.maxLon, lon),
            minLat: Math.min(result.minLat, lat),
            maxLat: Math.max(result.maxLat, lat),
        }),
        {
            minLon: Infinity,
            maxLon: -Infinity,
            minLat: Infinity,
            maxLat: -Infinity,
        },
    );
    const width = Math.max(bounds.maxLon - bounds.minLon, 0.01);
    const height = Math.max(bounds.maxLat - bounds.minLat, 0.01);
    const scale = 84 / Math.max(width, height);
    const offsetX = (100 - width * scale) / 2;
    const offsetY = (100 - height * scale) / 2;
    return `${ring
        .map(([lon, lat], index) => {
            const x = offsetX + (lon - bounds.minLon) * scale;
            const y = offsetY + (bounds.maxLat - lat) * scale;
            return `${index === 0 ? "M" : "L"}${x.toFixed(1)} ${y.toFixed(1)}`;
        })
        .join(" ")} Z`;
}

function toGeoShape(ring: Point[]): GeoShape {
    const bounds = ring.reduce(
        (result, [lon, lat]) => ({
            minLon: Math.min(result.minLon, lon),
            maxLon: Math.max(result.maxLon, lon),
            minLat: Math.min(result.minLat, lat),
            maxLat: Math.max(result.maxLat, lat),
        }),
        {
            minLon: Infinity,
            maxLon: -Infinity,
            minLat: Infinity,
            maxLat: -Infinity,
        },
    );
    return {
        path: `${ring
            .map(
                ([lon, lat], index) =>
                    `${index === 0 ? "M" : "L"}${lon.toFixed(3)} ${(-lat).toFixed(3)}`,
            )
            .join(" ")} Z`,
        bounds,
    };
}

const raw = JSON.parse(await readFile(inputPath, "utf8")) as {
    features: Feature[];
};
const shapes: Record<string, string> = {};
const geoShapes: Record<string, GeoShape> = {};

for (const feature of raw.features) {
    const properties = feature.properties;
    const geometry = feature.geometry;
    if (
        !properties ||
        !geometry ||
        properties.SOVEREIGNT !== properties.ADMIN ||
        properties.UN_A3 === "-099" ||
        properties.TYPE === "Indeterminate"
    )
        continue;

    const iso2 =
        properties.ISO_A2 === "-99" ? properties.ISO_A2_EH : properties.ISO_A2;
    if (!iso2 || !geometry.coordinates) continue;
    const rings: Point[][] =
        geometry.type === "Polygon"
            ? (geometry.coordinates as Point[][])
            : (geometry.coordinates as Point[][][]).flat();
    const exterior = rings.sort((a, b) => ringArea(b) - ringArea(a))[0];
    if (exterior) {
        // Keep result thumbnails compact, but retain much more of the
        // Natural Earth 50m coastline for the contextual Compass window.
        shapes[iso2] = toPath(simplify(exterior, 28));
        geoShapes[iso2] = toGeoShape(simplify(exterior, 180));
    }
}

const header = `// AUTO-GENERATED by scripts/build-compass-shapes.ts.\n\nexport interface GeoShape {\n    path: string;\n    bounds: {\n        minLon: number;\n        maxLon: number;\n        minLat: number;\n        maxLat: number;\n    };\n}\n`;
await writeFile(
    outputPath,
    `${header}export const compassCountryShapes: Record<string, string> = ${JSON.stringify(shapes, null, 4)};\n\nexport const compassCountryGeoShapes: Record<string, GeoShape> = ${JSON.stringify(geoShapes, null, 4)};\n`,
    "utf8",
);
console.log(`Wrote ${Object.keys(shapes).length} Compass country shapes`);
